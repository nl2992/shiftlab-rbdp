"""Write the rows of the paper's multi-state premium table from kstate_premium_v{1,2}.jsonl.

Run from the repo root:
    uv run --no-sync python scripts/paper4_continuation/rbdp/kstate/make_kstate_table.py
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[4]
RES = ROOT / "docs/paper4_continuation/rbdp/results"
OUT = ROOT / "paper/p4_tmlr/tables/kstate_rows.tex"
TS = [8, 16, 20, 24, 32, 48, 64, 100]

rows = [json.loads(line) for f in ("kstate_premium_v1.jsonl", "kstate_premium_v2.jsonl")
        for line in open(RES / f)]
cell = {(r["K"], r["eta"], r["B"], r["T"]): r for r in rows}
lines = []
for K in (3, 4):
    for eta in ("2/3", "3/4", "9/10"):
        for B in (1, 2, 3, 4):
            rs = [r for (k, e, b, _), r in cell.items() if (k, e, b) == (K, eta, B)]
            if not rs:
                continue
            vals = [f"{cell[(K, eta, B, T)]['rho']:.4f}" if (K, eta, B, T) in cell else "--" for T in TS]
            risk = max(r["risk_causal_iidpol"] for r in rs) / 0.1
            lines.append(f"{K} & ${eta}$ & {B} & " + " & ".join(vals) + f" & {risk:.0f}\\\\")
    if K == 3:
        lines.append("\\midrule")
OUT.write_text("% Generated by scripts/paper4_continuation/rbdp/kstate/make_kstate_table.py\n" + "\n".join(lines) + "\n")
print(OUT.read_text())
